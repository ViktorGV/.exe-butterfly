// A stable random id for this browser. crypto.randomUUID only exists in secure contexts (https or
// localhost), so over a plain-http LAN address (http://10.x.x.x:5173) it is undefined and calling it
// throws. getRandomValues works everywhere, so use it as the fallback and format as a v4 UUID.
export function newClientId(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6]! & 0x0f) | 0x40;
  b[8] = (b[8]! & 0x3f) | 0x80;
  const hex = Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
